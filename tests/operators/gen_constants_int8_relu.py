"""Regenerate constants_int8_relu.hpp: int8 RELU / RELU6 results from TFLite.

Needs TensorFlow (pip install tensorflow). Run from the repo root:
    python tests/operators/gen_constants_int8_relu.py tests/operators/constants_int8_relu.hpp

A model whose input goes straight into ReLU / ReLU(6) keeps a standalone
int8 RELU / RELU6 op, with an output scale different from the input's (the
converter calibrates the output range after the activation). Run with the
reference kernels (BUILTIN_REF).
"""
import sys

import numpy as np
import tensorflow as tf

N = 256


def case(name, max_value, rng):
    x_in = tf.keras.Input((N,))
    m = tf.keras.Model(x_in, tf.keras.layers.ReLU(max_value=max_value)(x_in))

    def rep():
        for _ in range(64):
            yield [rng.uniform(-7.3, 9.1, (1, N)).astype(np.float32)]

    c = tf.lite.TFLiteConverter.from_keras_model(m)
    c.optimizations = [tf.lite.Optimize.DEFAULT]
    c.representative_dataset = rep
    c.target_spec.supported_ops = [tf.lite.OpsSet.TFLITE_BUILTINS_INT8]
    c.inference_input_type = tf.int8
    c.inference_output_type = tf.int8
    it = tf.lite.Interpreter(
        model_content=c.convert(),
        experimental_op_resolver_type=tf.lite.experimental.OpResolverType.BUILTIN_REF)
    it.allocate_tensors()
    ops = [o["op_name"] for o in it._get_ops_details()]
    assert ops == (["RELU"] if max_value is None else ["RELU6"]), ops
    d, od = it.get_input_details()[0], it.get_output_details()[0]
    x = np.arange(-128, 128, dtype=np.int8).reshape(1, N)  # every int8 value
    it.set_tensor(d["index"], x)
    it.invoke()
    y = it.get_tensor(od["index"]).reshape(-1)
    (si, zi), (so, zo) = d["quantization"], od["quantization"]
    return "\n".join([
        "// %s: TFLite %s, input = every int8 value -128..127" % (name, ops[0]),
        "const float %s_in_scale = %.9ef; const int32_t %s_in_zp = %d;" % (name, si, name, zi),
        "const float %s_out_scale = %.9ef; const int32_t %s_out_zp = %d;" % (name, so, name, zo),
        "const int8_t %s_out[%d] = {%s};" % (name, N, ", ".join(str(int(v)) for v in y)),
    ])


if __name__ == "__main__":
    rng = np.random.default_rng(7)
    text = "\n".join([
        "// Generated by tests/operators/gen_constants_int8_relu.py with TensorFlow %s." % tf.__version__,
        "#ifndef CONSTANTS_INT8_RELU_HPP\n#define CONSTANTS_INT8_RELU_HPP\n#include <stdint.h>\n",
        case("relu_i8", None, rng) + "\n",
        case("relu6_i8", 6.0, rng),
        "\n#endif\n"])
    with open(sys.argv[1], "w") as f:  # the converter prints to stdout
        f.write(text)
