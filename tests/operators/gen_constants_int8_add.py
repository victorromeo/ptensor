"""Regenerate constants_int8_add.hpp: int8 ADD results from TFLite itself.

Needs TensorFlow (pip install tensorflow). Run from the repo root:
    python tests/operators/gen_constants_int8_add.py tests/operators/constants_int8_add.hpp

Two cases: ADD with no activation (output range has negatives) and ADD with
a fused RELU (the converter folds a ReLU after Add into the ADD op). Both
run with TFLite's reference kernels (BUILTIN_REF).
"""
import numpy as np
import tensorflow as tf

N = 64


def build(relu, rng):
    a_in, b_in = tf.keras.Input((N,)), tf.keras.Input((N,))
    y = tf.keras.layers.Add()([a_in, b_in])
    if relu:
        y = tf.keras.layers.ReLU()(y)
    m = tf.keras.Model([a_in, b_in], y)

    def rep():
        for _ in range(64):
            yield [rng.uniform(-6.2, 6.6, (1, N)).astype(np.float32),
                   rng.uniform(-14.8, 13.2, (1, N)).astype(np.float32)]

    c = tf.lite.TFLiteConverter.from_keras_model(m)
    c.optimizations = [tf.lite.Optimize.DEFAULT]
    c.representative_dataset = rep
    c.target_spec.supported_ops = [tf.lite.OpsSet.TFLITE_BUILTINS_INT8]
    c.inference_input_type = tf.int8
    c.inference_output_type = tf.int8
    it = tf.lite.Interpreter(
        model_content=c.convert(),
        experimental_op_resolver_type=tf.lite.experimental.OpResolverType.BUILTIN_REF)
    it.allocate_tensors()
    ops = [o["op_name"] for o in it._get_ops_details()]
    assert ops == ["ADD"], ops
    return it


def case(name, relu, rng):
    it = build(relu, rng)
    ins = sorted(it.get_input_details(), key=lambda d: d["index"])
    out = it.get_output_details()[0]
    xs = [rng.integers(-128, 128, (1, N), dtype=np.int8) for _ in ins]
    for d, x in zip(ins, xs):
        it.set_tensor(d["index"], x)
    it.invoke()
    y = it.get_tensor(out["index"]).reshape(-1)

    def arr(v):
        return ", ".join(str(int(t)) for t in v.reshape(-1))

    lines = ["// %s: %s" % (name, "ADD + fused RELU" if relu else "ADD, no activation")]
    for tag, d, x in (("a", ins[0], xs[0]), ("b", ins[1], xs[1])):
        s, zp = d["quantization"]
        lines.append("const float %s_%s_scale = %.9ef; const int32_t %s_%s_zp = %d;" % (name, tag, s, name, tag, zp))
        lines.append("const int8_t %s_%s[%d] = {%s};" % (name, tag, N, arr(x)))
    s, zp = out["quantization"]
    lines.append("const float %s_out_scale = %.9ef; const int32_t %s_out_zp = %d;" % (name, s, name, zp))
    lines.append("const int8_t %s_out[%d] = {%s};" % (name, N, arr(y)))
    return "\n".join(lines)


if __name__ == "__main__":
    import sys
    rng = np.random.default_rng(2026)
    text = "\n".join([
        "// Generated by tests/operators/gen_constants_int8_add.py with TensorFlow %s." % tf.__version__,
        "#ifndef CONSTANTS_INT8_ADD_HPP\n#define CONSTANTS_INT8_ADD_HPP\n#include <stdint.h>\n",
        "const int int8_add_n = %d;\n" % N,
        case("add_none", False, rng) + "\n",
        case("add_relu", True, rng),
        "\n#endif\n"])
    with open(sys.argv[1], "w") as f:  # the converter prints to stdout
        f.write(text)
